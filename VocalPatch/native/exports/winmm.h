/*
 * exports/winmm.h — every entry point System32\winmm.dll exports by name.
 *
 * build_proxy.ps1 copies this file into the build directory as proxy_exports.h.
 *
 * Why the whole table and not just what today's editors import:
 * a statically imported DLL must satisfy *every* import of *every* module that
 * loads it, or the DLL (and therefore the editor) fails to start. winmm is
 * pulled in by the main editor, by its audio stack and by plugins, and the set
 * differs per version — CeVIO, for instance, only reaches winmm through
 * MediaSuite.dll / CeVIO.Audio.dll, which want the whole waveIn/waveOut/mmio
 * families that SynthV and VoiSona never touch.
 *
 * The list is generated from the real export table, and each entry is forwarded
 * by VP_FWD_ANY (see proxy_engine.c): eight pointer-sized arguments in, one
 * pointer-sized result out. Over-declaring is ABI-safe on x64, under-declaring
 * is not, and no winmm entry point takes a float or a struct by value.
 *
 * Regenerate after a Windows update added exports:
 *   powershell -ExecutionPolicy Bypass -File .\tools\pe-exports.ps1 `
 *       -Path C:\Windows\System32\winmm.dll
 */
