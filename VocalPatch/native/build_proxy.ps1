# build_proxy.ps1 - build a drop-in proxy DLL for the VocalPatch editors.
#
# The proxy is one file you copy into an editor's own folder. The editor loads
# it automatically at startup (the name is in its import table and is not a
# KnownDLL); its DllMain then hosts the VocalPatch runtime, and every call to
# the shimmed entry point is forwarded to the real System32 DLL.
#
#   .\native\build_proxy.ps1                     # winmm.dll (SynthV, VoiSona, Piapro)
#   .\native\build_proxy.ps1 -Target hostfxr     # hostfxr.dll (OpenUtau)
#   .\native\build_proxy.ps1 -Test               # winmm + a self-test host
#
# -Target picks native\exports\<target>.h (the entry points to re-export).
# The loader path is baked in from ..\dist\payload so the result is a genuine
# one-file drop-in; the runtime also honours VOCALPATCH_LOADER and a
# vocalpatch.ini "loader=" line beside the proxy.
#
# Built with TinyCC: this build needs __attribute__((dllexport)), not
# __declspec(dllexport), which it rejects on a function definition.

[CmdletBinding()]
param(
    [string] $Target = 'winmm',
    [string] $LoaderPath,
    [string] $OutDir,
    [string] $RealDll,
    [string] $Importers,
    [switch] $Test
)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot      # VocalPatch\

$engine = Join-Path $PSScriptRoot 'proxy_engine.c'
$exports = Join-Path $PSScriptRoot "exports\$Target.h"
if (-not (Test-Path $exports)) { throw "unknown target '$Target' (no native\exports\$Target.h)" }

if (-not $OutDir) { $OutDir = Join-Path $PSScriptRoot 'out\dropin' }
if (-not (Test-Path $OutDir)) { New-Item -ItemType Directory -Force -Path $OutDir | Out-Null }

if (-not $LoaderPath) {
    $LoaderPath = Join-Path $root 'dist\payload\vocalpatch_loader.dll'
    if (-not (Test-Path $LoaderPath)) {
        $LoaderPath = Join-Path $root 'native\out\vocalpatch_loader_x64.dll'
    }
}

function Find-TinyCC64 {
    $candidates = @(
        (Join-Path $env:TEMP 'tcc\tcc\tcc.exe'),
        (Join-Path $env:TEMP 'tcc64\tcc\tcc.exe'),
        'C:\tcc\tcc.exe'
    )
    foreach ($candidate in $candidates) {
        if (-not (Test-Path $candidate)) { continue }
        $version = (& $candidate -v 2>&1 | Out-String)
        if ($version -match 'x86_64') { return $candidate }
    }
    throw 'a 64-bit TinyCC was not found (looked in %TEMP%\tcc, %TEMP%\tcc64, C:\tcc)'
}

$tcc = Find-TinyCC64
Write-Host "compiler : $tcc"
Write-Host "target   : $Target  (exports from native\exports\$Target.h)"

# Generated headers live beside the output so the build is reproducible.
$build = Join-Path $OutDir "_build_$Target"
if (Test-Path $build) { Remove-Item $build -Recurse -Force }
New-Item -ItemType Directory -Force -Path $build | Out-Null
Copy-Item $exports (Join-Path $build 'proxy_exports.h') -Force

$escaped = $LoaderPath -replace '\\', '\\'
@"
/* generated by build_proxy.ps1 - do not edit */
#define VP_TARGET_FILE "$Target.dll"
#define VP_LOADER_DEFAULT "$escaped"
"@ | Set-Content -Path (Join-Path $build 'vocalpatch_proxy_config.h') -Encoding ASCII
@"
/* generated by build_proxy.ps1 - do not edit */
#define VP_TARGET_FILE "$Target.dll"
#define VP_TARGET_BASE "$Target"
"@ | Set-Content -Path (Join-Path $build 'proxy_target.h') -Encoding ASCII

Write-Host "loader   : $LoaderPath"

$dll = Join-Path $OutDir "$Target.dll"
& $tcc -shared -O2 -o $dll $engine "-I$build" -DVP_HAVE_CONFIG -lkernel32
if ($LASTEXITCODE -ne 0 -or -not (Test-Path $dll)) { throw "build failed (tcc exit $LASTEXITCODE)" }
Write-Host ("built    : {0} ({1:N0} bytes)" -f $dll, (Get-Item $dll).Length)

# Two checks, and the second is the one that matters in practice:
#
#   1. every entry point we export must exist in the genuine DLL, or a forwarder
#      resolves to NULL and the host crashes the first time it calls it;
#   2. every entry point the *host* imports from us must be exported by us, or the
#      DLL fails to load - which takes the whole editor down with it.
#
# -RealDll overrides the genuine DLL to compare against (hostfxr has no System32
# copy; the app ships its own, and the builds differ per .NET version).
# -Importers is a ';'-separated list of exes/dlls whose imports of <target> must
# be covered.
$exportsScript = Join-Path $PSScriptRoot '..\tools\pe-exports.ps1'
$importsScript = Join-Path $PSScriptRoot '..\tools\pe-imports.ps1'
if (-not $RealDll) { $RealDll = Join-Path $env:SystemRoot "System32\$Target.dll" }

$ours = @(& $exportsScript -Path $dll -NamesOnly | Where-Object { $_ -match '^[A-Za-z_][A-Za-z0-9_]*$' })

if ((Test-Path $exportsScript) -and (Test-Path $RealDll)) {
    $real = @(& $exportsScript -Path $RealDll -NamesOnly | Where-Object { $_ -match '^[A-Za-z_][A-Za-z0-9_]*$' })
    $missing = @($ours | Where-Object { $real -notcontains $_ })
    if ($missing.Count) {
        Write-Warning ("exports that do not exist in {0}: {1}" -f (Split-Path $RealDll -Leaf), ($missing -join ', '))
    } else {
        Write-Host ("verified : all {0} exports exist in {1}" -f $ours.Count, (Split-Path $RealDll -Leaf))
    }
}

if ($Importers -and (Test-Path $importsScript)) {
    $gaps = 0
    foreach ($importer in ($Importers -split ';' | ForEach-Object { $_.Trim() } | Where-Object { $_ })) {
        if (-not (Test-Path -LiteralPath $importer)) { Write-Warning "importer not found: $importer"; continue }

        # -FunctionsOnly emits bare names on the pipeline, so the list survives the call.
        $need = @(& $importsScript -Path $importer -Only "$Target.dll" -FunctionsOnly |
                    Where-Object { $_ -and $_ -notmatch '^#' })

        $absent = @($need | Where-Object { $ours -notcontains $_ })
        if ($absent.Count) {
            Write-Warning ("{0} imports {1} entry point(s) this shim does not export: {2}" -f
                (Split-Path $importer -Leaf), $absent.Count, ($absent -join ', '))
            $gaps += $absent.Count
        } else {
            Write-Host ("covered  : {0} - all {1} of its {2} import(s) are exported" -f
                (Split-Path $importer -Leaf), $need.Count, $Target)
        }
    }
    if ($gaps) { throw "$gaps imported entry point(s) are missing from the shim" }
}

if ($Test) {
    if ($Target -ne 'winmm') { throw '-Test is only implemented for the winmm target' }
    Write-Host ''
    Write-Host 'building the throwaway host (a static winmm importer)'
    $hostExe = Join-Path $OutDir 'synthv-studio.exe'
    & $tcc -o $hostExe (Join-Path $PSScriptRoot 'proxy_test.c') (Join-Path $PSScriptRoot 'winmm.def')
    if ($LASTEXITCODE -ne 0) { throw "test host build failed (tcc exit $LASTEXITCODE)" }

    $stage = Join-Path $env:TEMP 'vp-dropin-test'
    if (Test-Path $stage) { Remove-Item $stage -Recurse -Force }
    $plain = Join-Path $stage 'baseline'
    $patched = Join-Path $stage 'patched'
    New-Item -ItemType Directory -Force -Path $plain, $patched | Out-Null
    Copy-Item $hostExe $plain -Force
    Copy-Item $hostExe $patched -Force
    Copy-Item $dll $patched -Force

    $loaderLog = Join-Path $env:TEMP 'vocalpatch-loader.log'
    Remove-Item $loaderLog -Force -ErrorAction SilentlyContinue

    Write-Host ''
    Write-Host 'case 1: baseline (no proxy) - Windows resolves the real System32 DLL'
    Push-Location $plain
    & (Join-Path $plain 'synthv-studio.exe') | Out-Null
    Pop-Location
    Start-Sleep -Milliseconds 400
    $baseline = (Get-Content (Join-Path $plain 'proxy_test_result.txt') -Raw).Trim()
    Write-Host "  $baseline"

    Write-Host 'case 2: proxy dropped in beside the exe'
    Push-Location $patched
    & (Join-Path $patched 'synthv-studio.exe') | Out-Null
    Pop-Location
    Start-Sleep -Milliseconds 1500
    $withProxy = (Get-Content (Join-Path $patched 'proxy_test_result.txt') -Raw).Trim()
    Write-Host "  $withProxy"

    $baselineDelta = [int]([regex]::Match($baseline, 'delta=(\d+)').Groups[1].Value)
    $proxyDelta = [int]([regex]::Match($withProxy, 'delta=(\d+)').Groups[1].Value)
    $proxyPidMatch = [regex]::Match($withProxy, 'pid=(\d+)')
    $proxyPid = if ($proxyPidMatch.Success) { [int]$proxyPidMatch.Groups[1].Value } else { 0 }

    $attached = @(Select-String -Path $loaderLog -Pattern 'attached' -ErrorAction SilentlyContinue)
    Write-Host ''
    Write-Host 'verdict:'
    Write-Host ("  - {0}" -f $(if ($baselineDelta -gt 0 -and $proxyDelta -gt 0) { 'forwarding works (the clock advances in both runs)' } else { 'FAILED: clock did not advance' }))
    Write-Host ("  - {0}" -f $(if ($withProxy -match 'beginPeriod=0') { 'timeBeginPeriod returned TIMERR_NOERROR through the proxy' } else { 'FAILED: timeBeginPeriod through the proxy' }))
    Write-Host ("  - {0}" -f $(if ($attached.Count -gt 0) { "the VocalPatch runtime loaded in the proxied run (pid $proxyPid)" } else { 'NOTE: no loader attach seen (check the baked loader path)' }))
}
